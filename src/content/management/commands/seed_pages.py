class Command(BaseCommand):
    help = "Ідемпотентний seed стандартних текстів статичних сторінок (about/delivery/offer/privacy)."

    def add_arguments(self, parser):
        parser.add_argument(
            "--force",
            action="store_true",
            help="Перезаписати сторінки, навіть якщо вони вже мають непорожній вміст (обережно — затре ручні правки).",
        )

    def handle(self, *args, **options):
        force = options["force"]
        created, updated, skipped = 0, 0, 0

        for slug, data in PAGES.items():
            page, is_created = Page.objects.get_or_create(
                slug=slug,
                defaults={
                    "title": data["title"],
                    "body": data["body"].strip(),
                    "meta_description": data["meta_description"],
                    "is_published": True,
                },
            )
            if is_created:
                created += 1
                self.stdout.write(self.style.SUCCESS(f"[+] Створено сторінку: {slug}"))
                continue

            if page.body.strip() and not force:
                skipped += 1
                self.stdout.write(f"[=] Пропущено (вже має вміст): {slug} — використайте --force для перезапису")
                continue

            page.title = data["title"]
            page.body = data["body"].strip()
            page.meta_description = data["meta_description"]
            page.save(update_fields=["title", "body", "meta_description"])
            updated += 1
            self.stdout.write(self.style.WARNING(f"[~] Оновлено сторінку: {slug}"))

        self.stdout.write(
            self.style.SUCCESS(
                f"\nГотово. Створено: {created}, оновлено: {updated}, пропущено: {skipped}."
            )
        )
